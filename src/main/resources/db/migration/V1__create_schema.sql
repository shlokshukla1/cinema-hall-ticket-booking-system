-- Portable SQL: runs unchanged on PostgreSQL and on H2 in PostgreSQL mode.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'STAFF', 'ADMIN'))
);

CREATE TABLE genres (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    CONSTRAINT uq_genres_name UNIQUE (name)
);

CREATE TABLE movies (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(200) NOT NULL,
    description      VARCHAR(2000),
    duration_minutes INT          NOT NULL,
    language         VARCHAR(60)  NOT NULL,
    certificate      VARCHAR(10)  NOT NULL,
    release_date     DATE         NOT NULL,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_movies_duration CHECK (duration_minutes BETWEEN 1 AND 600)
);
CREATE INDEX ix_movies_active_title ON movies (active, title);

CREATE TABLE movie_genres (
    movie_id BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,
    PRIMARY KEY (movie_id, genre_id),
    CONSTRAINT fk_movie_genres_movie FOREIGN KEY (movie_id) REFERENCES movies (id) ON DELETE CASCADE,
    CONSTRAINT fk_movie_genres_genre FOREIGN KEY (genre_id) REFERENCES genres (id)
);
CREATE INDEX ix_movie_genres_genre ON movie_genres (genre_id);

CREATE TABLE theatres (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(120) NOT NULL,
    city    VARCHAR(80)  NOT NULL,
    address VARCHAR(255) NOT NULL,
    active  BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_theatres_name_city UNIQUE (name, city)
);
CREATE INDEX ix_theatres_city ON theatres (city);

CREATE TABLE screens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theatre_id BIGINT      NOT NULL,
    name       VARCHAR(60) NOT NULL,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_screens_theatre FOREIGN KEY (theatre_id) REFERENCES theatres (id),
    CONSTRAINT uq_screens_theatre_name UNIQUE (theatre_id, name)
);

CREATE TABLE seat_categories (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(40)   NOT NULL,
    default_price NUMERIC(10, 2) NOT NULL,
    sort_order    INT           NOT NULL DEFAULT 0,
    CONSTRAINT uq_seat_categories_name UNIQUE (name),
    CONSTRAINT ck_seat_categories_price CHECK (default_price >= 0)
);

CREATE TABLE seats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id   BIGINT     NOT NULL,
    category_id BIGINT     NOT NULL,
    row_label   VARCHAR(4) NOT NULL,
    seat_number INT        NOT NULL,
    active      BOOLEAN    NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_seats_screen FOREIGN KEY (screen_id) REFERENCES screens (id) ON DELETE CASCADE,
    CONSTRAINT fk_seats_category FOREIGN KEY (category_id) REFERENCES seat_categories (id),
    CONSTRAINT uq_seats_position UNIQUE (screen_id, row_label, seat_number),
    CONSTRAINT ck_seats_number CHECK (seat_number > 0)
);
CREATE INDEX ix_seats_category ON seats (category_id);

CREATE TABLE shows (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id   BIGINT      NOT NULL,
    screen_id  BIGINT      NOT NULL,
    start_time TIMESTAMP WITH TIME ZONE NOT NULL,
    end_time   TIMESTAMP WITH TIME ZONE NOT NULL,
    language   VARCHAR(60) NOT NULL,
    format     VARCHAR(20) NOT NULL,
    status     VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_shows_movie FOREIGN KEY (movie_id) REFERENCES movies (id),
    CONSTRAINT fk_shows_screen FOREIGN KEY (screen_id) REFERENCES screens (id),
    CONSTRAINT ck_shows_status CHECK (status IN ('SCHEDULED', 'CANCELLED')),
    CONSTRAINT ck_shows_times CHECK (end_time > start_time)
);
CREATE INDEX ix_shows_movie_start ON shows (movie_id, start_time);
CREATE INDEX ix_shows_screen_start ON shows (screen_id, start_time);
CREATE INDEX ix_shows_status_start ON shows (status, start_time);

CREATE TABLE seat_holds (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference    VARCHAR(36)    NOT NULL,
    user_id      BIGINT         NOT NULL,
    show_id      BIGINT         NOT NULL,
    status       VARCHAR(20)    NOT NULL,
    seat_count   INT            NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_seat_holds_reference UNIQUE (reference),
    CONSTRAINT fk_seat_holds_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_seat_holds_show FOREIGN KEY (show_id) REFERENCES shows (id),
    CONSTRAINT ck_seat_holds_status CHECK (status IN ('ACTIVE', 'CONFIRMED', 'RELEASED', 'EXPIRED')),
    CONSTRAINT ck_seat_holds_count CHECK (seat_count > 0)
);
CREATE INDEX ix_seat_holds_status_expiry ON seat_holds (status, expires_at);
CREATE INDEX ix_seat_holds_user_show ON seat_holds (user_id, show_id, status);

CREATE TABLE bookings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference          VARCHAR(16)    NOT NULL,
    ticket_token       VARCHAR(64)    NOT NULL,
    user_id            BIGINT         NOT NULL,
    show_id            BIGINT         NOT NULL,
    hold_id            BIGINT         NOT NULL,
    idempotency_key    VARCHAR(100)   NOT NULL,
    status             VARCHAR(20)    NOT NULL,
    total_amount       NUMERIC(10, 2) NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    cancelled_at       TIMESTAMP WITH TIME ZONE,
    cancellation_reason VARCHAR(40),
    checked_in_at      TIMESTAMP WITH TIME ZONE,
    checked_in_by      BIGINT,
    CONSTRAINT uq_bookings_reference UNIQUE (reference),
    CONSTRAINT uq_bookings_ticket_token UNIQUE (ticket_token),
    CONSTRAINT uq_bookings_hold UNIQUE (hold_id),
    CONSTRAINT uq_bookings_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_bookings_show FOREIGN KEY (show_id) REFERENCES shows (id),
    CONSTRAINT fk_bookings_hold FOREIGN KEY (hold_id) REFERENCES seat_holds (id),
    CONSTRAINT fk_bookings_checked_in_by FOREIGN KEY (checked_in_by) REFERENCES users (id),
    CONSTRAINT ck_bookings_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    -- A cancelled ticket can never have been used, and a used ticket can never be cancelled.
    CONSTRAINT ck_bookings_cancel_or_checkin CHECK (cancelled_at IS NULL OR checked_in_at IS NULL)
);
CREATE INDEX ix_bookings_user_created ON bookings (user_id, created_at);
CREATE INDEX ix_bookings_show_status ON bookings (show_id, status);
CREATE INDEX ix_bookings_created ON bookings (created_at);

-- One row per sellable seat per show. All seat state transitions happen on this row.
CREATE TABLE show_seats (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id         BIGINT         NOT NULL,
    seat_id         BIGINT         NOT NULL,
    price           NUMERIC(10, 2) NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    hold_id         BIGINT,
    hold_expires_at TIMESTAMP WITH TIME ZONE,
    booking_id      BIGINT,
    CONSTRAINT uq_show_seats_show_seat UNIQUE (show_id, seat_id),
    CONSTRAINT fk_show_seats_show FOREIGN KEY (show_id) REFERENCES shows (id),
    CONSTRAINT fk_show_seats_seat FOREIGN KEY (seat_id) REFERENCES seats (id),
    CONSTRAINT fk_show_seats_hold FOREIGN KEY (hold_id) REFERENCES seat_holds (id),
    CONSTRAINT fk_show_seats_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT ck_show_seats_price CHECK (price >= 0),
    -- Makes half-applied states such as "BOOKED without a booking" unrepresentable.
    CONSTRAINT ck_show_seats_state CHECK (
        (status = 'AVAILABLE' AND hold_id IS NULL AND hold_expires_at IS NULL AND booking_id IS NULL)
        OR (status = 'HELD' AND hold_id IS NOT NULL AND hold_expires_at IS NOT NULL AND booking_id IS NULL)
        OR (status = 'BOOKED' AND hold_id IS NULL AND hold_expires_at IS NULL AND booking_id IS NOT NULL)
    )
);
CREATE INDEX ix_show_seats_show_status ON show_seats (show_id, status);
CREATE INDEX ix_show_seats_hold ON show_seats (hold_id);
CREATE INDEX ix_show_seats_booking ON show_seats (booking_id);
CREATE INDEX ix_show_seats_seat ON show_seats (seat_id);

CREATE TABLE booking_seats (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id          BIGINT         NOT NULL,
    show_seat_id        BIGINT         NOT NULL,
    seat_label          VARCHAR(12)    NOT NULL,
    category_name       VARCHAR(40)    NOT NULL,
    price               NUMERIC(10, 2) NOT NULL,
    -- Equals show_seat_id while the booking is live, NULL once cancelled. The UNIQUE constraint is the
    -- database's last line of defence: two live bookings can never own one seat, whatever the app does.
    active_show_seat_id BIGINT,
    CONSTRAINT uq_booking_seats_active UNIQUE (active_show_seat_id),
    CONSTRAINT uq_booking_seats_pair UNIQUE (booking_id, show_seat_id),
    CONSTRAINT fk_booking_seats_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fk_booking_seats_show_seat FOREIGN KEY (show_seat_id) REFERENCES show_seats (id),
    CONSTRAINT ck_booking_seats_active CHECK (active_show_seat_id IS NULL OR active_show_seat_id = show_seat_id)
);
CREATE INDEX ix_booking_seats_show_seat ON booking_seats (show_seat_id);

CREATE TABLE payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id      BIGINT         NOT NULL,
    provider_ref    VARCHAR(40)    NOT NULL,
    method          VARCHAR(20)    NOT NULL,
    amount          NUMERIC(10, 2) NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    refund_amount   NUMERIC(10, 2) NOT NULL DEFAULT 0,
    refund_percent  INT            NOT NULL DEFAULT 0,
    refund_status   VARCHAR(20)    NOT NULL DEFAULT 'NONE',
    refunded_at     TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_payments_booking UNIQUE (booking_id),
    CONSTRAINT uq_payments_provider_ref UNIQUE (provider_ref),
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT ck_payments_method CHECK (method IN ('CARD', 'UPI', 'WALLET')),
    CONSTRAINT ck_payments_status CHECK (status IN ('CAPTURED')),
    CONSTRAINT ck_payments_refund_status CHECK (refund_status IN ('NONE', 'NOT_ELIGIBLE', 'SIMULATED_REFUNDED')),
    CONSTRAINT ck_payments_refund_amount CHECK (refund_amount >= 0 AND refund_amount <= amount),
    CONSTRAINT ck_payments_refund_percent CHECK (refund_percent BETWEEN 0 AND 100)
);
CREATE INDEX ix_payments_created ON payments (created_at);

CREATE TABLE cancellation_rules (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_hours_before INT NOT NULL,
    refund_percent   INT NOT NULL,
    CONSTRAINT uq_cancellation_rules_hours UNIQUE (min_hours_before),
    CONSTRAINT ck_cancellation_rules_hours CHECK (min_hours_before >= 0),
    CONSTRAINT ck_cancellation_rules_percent CHECK (refund_percent BETWEEN 0 AND 100)
);

CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT,
    actor_email VARCHAR(255) NOT NULL,
    action      VARCHAR(60)  NOT NULL,
    entity_type VARCHAR(40)  NOT NULL,
    entity_id   VARCHAR(64)  NOT NULL,
    details     VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_audit_logs_created ON audit_logs (created_at);
CREATE INDEX ix_audit_logs_action ON audit_logs (action, created_at);
CREATE INDEX ix_audit_logs_entity ON audit_logs (entity_type, entity_id);
